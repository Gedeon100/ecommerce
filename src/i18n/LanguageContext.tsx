interface LanguageContextValue {
  language: LanguageCode;
  currentLanguageOption: LanguageOption;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
  translateCategory: (cat: string) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
  language: 'fr',
  currentLanguageOption: SUPPORTED_LANGUAGES[0],
  setLanguage: () => {},
  t: (key, fallback) => fallback || TRANSLATIONS.fr[key] || key,
  translateCategory: (cat) => cat,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    if (typeof window === 'undefined') return 'fr';
    const saved = localStorage.getItem('beninmarket_lang') as LanguageCode | null;
    if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved)) {
      return saved;
    }
    return 'fr';
  });

  const currentLanguageOption =
    SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0];

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language === 'fon' ? 'fr' : language;
      document.documentElement.dir = currentLanguageOption.dir || 'ltr';
    }
  }, [language, currentLanguageOption]);

  const setLanguage = (lang: LanguageCode) => {
    setLanguageState(lang);
    if (typeof window !== 'undefined') {
      localStorage.setItem('beninmarket_lang', lang);
    }
  };

  const t = (key: string, fallback?: string): string => {
    return TRANSLATIONS[language]?.[key] || TRANSLATIONS.fr[key] || fallback || key;
  };

  const translateCategory = (cat: string): string => {
    if (language === 'fr') return cat;
    return CATEGORY_TRANSLATIONS[cat]?.[language] || cat;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        currentLanguageOption,
        setLanguage,
        t,
        translateCategory,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
